/** discussionSummary 최소 길이 — "ok", "합의함" 같은 형식적 통과를 막는다 */
const MIN_DISCUSSION_SUMMARY_LENGTH = 10;

/**
 * 합의 게이트 — 통과하면 null, 막히면 사용자에게 돌려줄 안내 문구를 반환.
 *
 * API를 호출하기 전에 MCP 핸들러 단계에서 판정하므로 웹 UI와 API 라우트는
 * 이 규칙의 영향을 전혀 받지 않는다.
 */
export function checkDesignAgreement(args: {
  userAgreement: "AGREED" | "NOT_DISCUSSED";
  discussionSummary: string;
}): string | null {
  if (args.userAgreement === "NOT_DISCUSSED") {
    return (
      "등록/수정을 진행하지 않았습니다. 사용자와 아직 합의되지 않은 설계 변경입니다.\n\n" +
      "다음 순서로 진행하세요:\n" +
      "1. 지금 등록하려던 내용을 사용자에게 설명하고 의견을 받습니다.\n" +
      "2. 특히 설계 단위(영역을 몇 개로 나눌지)는 사용자 확인을 받습니다.\n" +
      "3. 합의된 뒤 userAgreement=AGREED 와 합의 내용 요약으로 다시 호출하세요."
    );
  }

  if (args.discussionSummary.trim().length < MIN_DISCUSSION_SUMMARY_LENGTH) {
    return (
      "등록/수정을 진행하지 않았습니다. discussionSummary 가 너무 짧습니다.\n\n" +
      `사용자와 무엇을 합의했는지 ${MIN_DISCUSSION_SUMMARY_LENGTH}자 이상으로 구체적으로 적어주세요. ` +
      "형식적으로 채우는 값이 아니라, 합의 내용을 확인하기 위한 기록입니다."
    );
  }

  return null;
}

