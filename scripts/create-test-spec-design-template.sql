-- tb_ai_design_template — 테스트 명세서(TEST_SPEC) 시스템 공통 양식 시드
--
-- 목적:
--   AI(MCP)와 사람이 테스트 명세서 본문(test_spec_dc)과 케이스 문장을 쓸 때
--   참고할 표준 양식을 등록한다. 설계 5계층 양식과 같은 테이블·같은 resolve
--   경로를 쓰므로 관리 화면(설계 양식)에서 그대로 편집할 수 있다.
--
-- 정책:
--   prjct_id IS NULL → 시스템 공통 (모든 프로젝트에 노출)
--   프로젝트 전용 양식이 있으면 resolve 에서 그쪽이 우선한다.
--
-- 멱등성: ref_ty_code='TEST_SPEC' 시스템 공통 행이 이미 있으면 INSERT 스킵.
-- ────────────────────────────────────────────────────────────────────────

DO $$
DECLARE
  seed_count INTEGER;
BEGIN
  SELECT COUNT(*) INTO seed_count
    FROM tb_ai_design_template
   WHERE prjct_id IS NULL AND ref_ty_code = 'TEST_SPEC';

  IF seed_count > 0 THEN
    RAISE NOTICE 'TEST_SPEC 시스템 공통 양식 % 건 이미 존재 — 시드 INSERT 스킵', seed_count;
    RETURN;
  END IF;

  INSERT INTO tb_ai_design_template
    (dsgn_tmpl_id, prjct_id, ref_ty_code, tmpl_nm, tmpl_dc,
     example_cn, template_cn, use_yn, default_yn, sort_ordr)
  VALUES (
    gen_random_uuid()::text,
    NULL,
    'TEST_SPEC',
    '테스트 명세서 표준 양식',
    '테스트 명세서 개요와 케이스 문장 작성 기준. AI(MCP)가 케이스를 생성하기 전에 반드시 조회한다.',

    -- ── example_cn : 작성 예시 ────────────────────────────────────────
$EXAMPLE$
## 테스트 개요

**대상**: PID-00022 멤버 목록 (UW-00010 역할 관리)
