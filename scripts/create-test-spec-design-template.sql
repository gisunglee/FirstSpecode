### 기능 시나리오 예시

| 구분 | 테스트 내용 | 예상 결과 |
|------|------------|----------|
| 멤버 목록 | OWNER 계정으로 멤버 목록 화면에 진입한다 | 프로젝트 멤버 3명이 이름·이메일·역할과 함께 표시되고, 각 행에 [역할 변경] 버튼이 보인다 |
| 멤버 목록 | MEMBER 계정으로 멤버 목록 화면에 진입한다 | 멤버 목록은 동일하게 보이되 [역할 변경] 버튼이 나타나지 않는다 |
| 역할 변경 | OWNER 계정으로 MEMBER 한 명의 역할을 ADMIN 으로 변경하고 저장한다 | 확인 메시지가 뜬 뒤 저장되고, 목록의 해당 행 역할이 'ADMIN' 으로 갱신된다 |
| 역할 변경 | 마지막 남은 OWNER 의 역할을 MEMBER 로 변경한다 | 저장되지 않고 "프로젝트에는 최소 1명의 OWNER 가 필요합니다" 메시지가 표시된다 |
| 역할 변경 | 역할 변경 화면에서 아무것도 바꾸지 않고 [저장]을 누른다 | 변경 없이 화면이 닫히고 목록이 그대로 유지된다 |

