### 이 예시가 지키는 기준

- 케이스 단위는 **기능 1개당 정상 1건 + 예외 0~2건**. "저장 버튼", "취소 버튼"을
  각각 케이스로 만들지 않았다.
- 예상 결과는 **화면에서 눈으로 확인 가능한 문장**이다.
  "정상 동작한다", "에러가 난다" 같은 판정 불가 문장을 쓰지 않았다.
- 공통 점검은 **직접 쓰지 않고 마스터에서 가져온다**고만 적었다.
- 구분(grpNm)은 화면 안의 기능 묶음 이름이다.
